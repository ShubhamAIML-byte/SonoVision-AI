// Helper to generate SVG data URIs that look like real research paper tables and benchmark plots
function createPaperTableSvg(title: string, subtitle: string, rows: [string, string, string, string][]): string {
  const tableRowsSvg = rows
    .map(
      (r, i) => `
    <rect x="20" y="${90 + i * 28}" width="560" height="26" fill="${i % 2 === 0 ? "#1e293b" : "#0f172a"}" rx="3"/>
    <text x="35" y="${107 + i * 28}" fill="#38bdf8" font-family="monospace" font-size="11" font-weight="bold">${r[0]}</text>
    <text x="210" y="${107 + i * 28}" fill="#f1f5f9" font-family="monospace" font-size="11">${r[1]}</text>
    <text x="340" y="${107 + i * 28}" fill="#94a3b8" font-family="monospace" font-size="11">${r[2]}</text>
    <text x="470" y="${107 + i * 28}" fill="#34d399" font-family="monospace" font-size="11">${r[3]}</text>
  `
    )
    .join("");

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="360" viewBox="0 0 600 360" fill="none">
    <rect width="600" height="360" rx="12" fill="#090d16" stroke="#1e293b" stroke-width="2"/>
    <rect x="0" y="0" width="600" height="44" fill="#0f172a"/>
    <circle cx="24" cy="22" r="5" fill="#ef4444"/>
    <circle cx="40" cy="22" r="5" fill="#f59e0b"/>
    <circle cx="56" cy="22" r="5" fill="#10b981"/>
    <text x="76" y="26" fill="#94a3b8" font-family="sans-serif" font-size="12" font-weight="600">ArXiv Research Paper • Table 3: Comparative Benchmark</text>
    
    <text x="20" y="65" fill="#ffffff" font-family="sans-serif" font-size="14" font-weight="bold">${title}</text>
    <text x="20" y="80" fill="#64748b" font-family="sans-serif" font-size="10">${subtitle}</text>

    <!-- Table Header -->
    <rect x="20" y="86" width="560" height="2" fill="#38bdf8"/>
    
    ${tableRowsSvg}
    
    <line x1="20" y1="315" x2="580" y2="315" stroke="#334155" stroke-dasharray="3 3"/>
    <text x="20" y="335" fill="#64748b" font-family="monospace" font-size="10">Source: Published Peer-Reviewed Findings • Evaluated under Standardized Protocols</text>
  </svg>`;

  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

